function createRoadmapMilestones(
  projectId: string,
  definitions: Array<[suffix: string, title: string, definitionOfDone: string, status: ProjectSeed["milestones"][number]["status"], dueDate: string]>,
): ProjectSeed["milestones"] {
  return definitions.map(([suffix, title, definitionOfDone, status, dueDate], index) => ({
    id: `${projectId}-milestone-${suffix}`,
    projectId,
    title,
    definitionOfDone,
    predecessorIds: index === 0 ? [] : [`${projectId}-milestone-${definitions[index - 1][0]}`],
    status,
    dueDate,
    sortOrder: (index + 1) * 10,
    createdAt: roboticsRoadmapAt,
    updatedAt: roboticsRoadmapAt,
  }));
}

